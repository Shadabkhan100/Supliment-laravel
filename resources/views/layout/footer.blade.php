document.addEventListener("DOMContentLoaded", function () {

    const form = document.getElementById("newsletterFormX9");

    let userLat = null;
    let userLng = null;

    function getUserLocation() {
        if (!navigator.geolocation) return;

        navigator.geolocation.getCurrentPosition(
            function (position) {
                userLat = position.coords.latitude;
                userLng = position.coords.longitude;
            },
            function (error) {
                console.log(error.message);
            }
        );
    }

    getUserLocation();

    form.addEventListener("submit", function (e) {
        e.preventDefault();

        const emailInput = form.querySelector('input[type="email"]');
        const email = emailInput.value;

        if (!email) return;

        const submitBtn = form.querySelector("button");

        // ================= LOADER =================
        submitBtn.disabled = true;
        submitBtn.innerHTML = `<div class="spinnerX9"></div>`;

        fetch("/subscribe", {
            method: "POST",
            headers: {
                "Content-Type": "application/json",
                "X-CSRF-TOKEN": "{{ csrf_token() }}"
            },
            body: JSON.stringify({
                email: email,
                latitude: userLat,
                longitude: userLng
            })
        })
        .then(async (res) => {
            const data = await res.json();

            if (!res.ok) throw data;

            return data;
        })
        .then(data => {

            // ================= SUCCESS ALERT =================
            Swal.fire({
                icon: 'success',
                title: 'Subscribed!',
                text: data.message || 'You have been subscribed successfully',
                timer: 2000,
                showConfirmButton: false
            });

            // ================= CHECK ICON =================
            submitBtn.innerHTML = `
                <svg xmlns="http://www.w3.org/2000/svg" width="22" height="22" viewBox="0 0 24 24" fill="none">
                    <path d="M20 6L9 17L4 12"
                        stroke="#22c55e"
                        stroke-width="3"
                        stroke-linecap="round"
                        stroke-linejoin="round"/>
                </svg>
            `;

            setTimeout(() => {
                submitBtn.innerHTML = `
                    <svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 20 20" fill="none">
                        <path d="M19.8283 0.171647C19.6625 0.00586635 19.4138 -0.0451101 19.1963 0.041921L0.368218 7.57308C0.152789 7.65925 0.00853097 7.86441 0.00024974 8.09632C-0.00799243 8.32819 0.121382 8.54308 0.330132 8.64433L7.75465 12.2451L11.3555 19.6697C11.4537 19.8722 11.6588 19.9999 11.8826 19.9999C11.8895 19.9999 11.8965 19.9998 11.9035 19.9995C12.1353 19.9913 12.3406 19.847 12.4267 19.6316L19.9579 0.803599C20.045 0.585943 19.994 0.337389 19.8283 0.171647Z"
